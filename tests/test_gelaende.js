'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../web/gelaende.js'),'utf8'),context);
const api=context.window.MQL_GELAENDE;
assert.equal(api.preference({getItem:()=>null}),'gelaende');
assert.equal(api.preference({getItem:()=> 'karte'}),'karte');
assert.equal(api.preference({getItem:()=> 'gelaende'}),'gelaende');
assert.equal(api.preference({getItem:()=> 'broken'}),'gelaende');
assert.equal(api.preference({getItem:()=>{throw Error('denied');}}),'gelaende');
assert.equal(api.preference(null),'gelaende');
const map={mr:1,west:1,north:4,east:3,south:2};
assert.ok(api.frameMatches(map,{region:1,frame:[1,4,3,2]}));
assert.ok(!api.frameMatches(map,{region:2,frame:[1,4,3,2]}));
assert.ok(!api.frameMatches(map,{region:1,frame:[1,5,3,2]}));
assert.ok(api.frameMatches(map,{region:1,overview:true,frame:[0,10,8,-1]}));
assert.ok(!api.frameMatches(map,{region:1,overview:true}));
assert.ok(!api.frameMatches(map,{region:1,frame:[1,4,0,2]}));
console.log('Terrain preference, storage failure and region/frame guards OK');
