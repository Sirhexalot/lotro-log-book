'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const memory=new Map();
memory.set('mql.notizen','{"kept":true}');
memory.set('mql.charaktere','{"kept":true}');
memory.set('mql.kartenansicht','gelaende');
memory.set('mql.vorkommen','{"wahl":{"PROSPECTOR":"*"}}');
const storage={getItem:key=>memory.has(key)?memory.get(key):null,setItem:(key,value)=>memory.set(key,String(value))};
const context={window:{localStorage:storage}};vm.createContext(context);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../web/gelaende.js'),'utf8'),context);
const api=context.window.MQL_GELAENDE;
assert.equal(api.preference({getItem:()=>null}),'karte');
assert.equal(api.preference({getItem:()=> 'karte'}),'karte');
assert.equal(api.preference({getItem:()=> 'gelaende'}),'gelaende');
assert.equal(api.preference({getItem:()=> 'broken'}),'karte');
assert.equal(api.preference({getItem:()=>{throw Error('denied');}}),'karte');
assert.equal(api.preference(null),'karte');
assert.equal(memory.get('mql.kartenansicht'),'karte');
assert.equal(memory.get('mql.vorkommen'),'{"wahl":{}}');
assert.equal(memory.get('mql.notizen'),'{"kept":true}');
assert.equal(memory.get('mql.charaktere'),'{"kept":true}');
assert.equal(api.migratePreferences(storage),false,'migration is one-time');
let observed=[];
const unsubscribe=api.subscribePreference(mode=>observed.push(mode));
assert.equal(observed.at(-1),'karte');
api.setPreference('gelaende');
assert.equal(memory.get('mql.kartenansicht'),'gelaende');
assert.equal(observed.at(-1),'gelaende');
unsubscribe();
api.setPreference('karte');
assert.equal(observed.at(-1),'gelaende','unsubscribed controls stop receiving updates');
memory.set('mql.kartenansicht','gelaende');
memory.set('mql.vorkommen','{"wahl":{"PROSPECTOR":"ore"}}');
assert.equal(api.migratePreferences(storage),false,'existing preference changes survive later visits');
assert.equal(memory.get('mql.kartenansicht'),'gelaende');
assert.equal(memory.get('mql.vorkommen'),'{"wahl":{"PROSPECTOR":"ore"}}');
assert.equal(api.migratePreferences(null),false);
const map={mr:1,west:1,north:4,east:3,south:2};
assert.ok(api.frameMatches(map,{region:1,frame:[1,4,3,2]}));
assert.ok(!api.frameMatches(map,{region:2,frame:[1,4,3,2]}));
assert.ok(!api.frameMatches(map,{region:1,frame:[1,5,3,2]}));
assert.ok(api.frameMatches(map,{region:1,overview:true,frame:[0,10,8,-1]}));
assert.ok(!api.frameMatches(map,{region:1,overview:true}));
assert.ok(!api.frameMatches(map,{region:1,frame:[1,4,0,2]}));
console.log('One-time map defaults, storage failure and region/frame guards OK');
