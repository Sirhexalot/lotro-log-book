#!/usr/bin/env python3
"""Build the epic story as a view of its own.

The epic is not part of the map's catalogue path. Its volumes, books and
chapters come from the client's quest path (``theme:epic`` → ``volume`` →
``category``); the map app only lends its map, markers and detail pane.

Output: ``web/epik-<sprache>.js`` with the finished tree and the rows the view
needs. Nothing here changes ``daten-<sprache>.js`` or the map shards.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / 'web'
DATEN = ROOT / 'daten'
PLUGIN = ROOT.parent / 'MagicQuestLog' / 'plugin' / 'MagicQuestLog' / 'Data'
LANGS = ('de', 'en', 'fr')
NAME = {'de': 'Epische Geschichte', 'en': 'Epic Story', 'fr': 'Histoire épique'}
BAND = {'de': 'Band', 'en': 'Book', 'fr': 'Livre'}
# The largest game map; the view opens it in terrain. A chosen chapter still
# jumps to its own region through the map app.
WELTKARTE = 268437557
# Fields the view, the markers, the filter and the detail loader need.
KEEP = ('i', 'n', 'l', 'g', 'gt', 't', 'fk', 'f', 'ie', 'x', 'e', 'v', 'vo', 'vl',
        'vb', 'ls', 'mp')
PREFIX = re.compile(r'^(?:Epos|Episch|Epic|Épique|Epique|Histoire\s+épique)\s*[-–—:]\s*', re.I)
VOLUME = re.compile(r'^(?:Band|Vol\.?|Volume)\s+[IVXLCDM0-9]+\s*[,:]\s*', re.I)
PROLOG = re.compile(r'^(?:Prolog|Prologue|Vorwort)', re.I)
EPILOG = re.compile(r'^(?:Epilog|Epilogue|Nachwort|Afterword|Épilogue)', re.I)
ZWISCHEN = re.compile(r'^(?:Zwischenspiel|Interlude)', re.I)
GROUP_ORDER = ('270', '346', '407', '481')


def lua_rows(path: Path) -> list[dict]:
    """Read the exported quest path (theme/volume/category) without a Lua VM.

    The file is generated by the plugin in a regular shape; only id and the path
    parts are read here. Everything else comes from the built data.
    """
    text = path.read_text(encoding='utf-8')
    rows = []
    for chunk in text.split('\nt[')[1:]:
        if 'theme:epic' not in chunk:
            continue
        kennung = re.search(r'\["id"\]="([0-9A-F]{8})"', chunk)
        if not kennung:
            continue
        pfad = re.findall(r'\["k"\]="([^"]+)",\["n"\]="((?:[^"\\]|\\.)*)"', chunk)
        rows.append({'id': kennung.group(1),
                     'pfad': [(key, value.replace('\\"', '"').replace('\\\\', '\\'))
                              for key, value in pfad]})
    return rows


def assignment(text: str, name: str):
    match = re.search(r'window\.%s\s*=\s*' % re.escape(name), text)
    if not match:
        raise SystemExit('MISSING: %s' % name)
    return json.JSONDecoder().raw_decode(text[match.end():])[0]


def sauber(label: str, gruppe: str = '') -> str:
    label = PREFIX.sub('', label)
    label = VOLUME.sub('', label)
    if gruppe and label.lower().startswith(gruppe.lower() + ','):
        label = label[len(gruppe) + 1:].strip()
    return label.strip()


def roman(value: str) -> int:
    if value.isdigit():
        return int(value)
    zahlen = {'I': 1, 'V': 5, 'X': 10, 'L': 50, 'C': 100, 'D': 500, 'M': 1000}
    total, letzte = 0, 0
    for zeichen in reversed(value.upper()):
        wert = zahlen.get(zeichen, 0)
        total += -wert if wert < letzte else wert
        letzte = max(letzte, wert)
    return total


def ist_prolog(label: str) -> bool:
    """A prologue book (Prolog, Prologue, Vorwort) never counts as progress."""
    return bool(PROLOG.match(label or ''))


def buch_rang(label: str) -> tuple:
    if PROLOG.match(label):
        return (-1, 0, '')
    if ZWISCHEN.match(label):
        return (50, 0, '')
    if EPILOG.match(label):
        return (99, 0, '')
    treffer = re.match(r'^(?:Buch|Book|Livre)\s+([IVXLCDM]+|\d+)', label, re.I)
    if treffer:
        return (1, roman(treffer.group(1)), label)
    return (60, 0, label)


def kapitel_rang(name: str) -> tuple:
    if PROLOG.match(name) or re.search(r'\bProlog\b', name, re.I):
        return (-1, 0, 0)
    if ZWISCHEN.match(name) or re.search(r'\bZwischenspiel\b|\bInterlude\b', name, re.I):
        return (50, 0, 0)
    if EPILOG.match(name) or re.search(r'\bEpilog\b|\bNachwort\b|\bAfterword\b|\bÉpilogue\b', name, re.I):
        return (99, 0, 0)
    treffer = re.search(r'Kapitel\s+(\d+)(?:\.(\d+))?', name)
    if treffer:
        return (0, int(treffer.group(1)), int(treffer.group(2) or 0))
    return (60, 0, 0)


def geber_orte() -> dict:
    path = DATEN / 'auftraggeber.json'
    if not path.is_file():
        return {}
    daten = json.loads(path.read_text(encoding='utf-8'))
    givers = daten.get('givers') or {}
    zuordnung = daten.get('quest_giver') or {}
    orte = {}
    for kennung, geber in zuordnung.items():
        for eines in (geber if isinstance(geber, list) else [geber]):
            for platz in (givers.get(str(eines)) or {}).get('places') or []:
                if platz.get('map') is None or platz.get('lat') is None or platz.get('lon') is None:
                    continue
                orte[str(kennung).upper()] = [int(platz['map']),
                                              round(float(platz['lat']), 5),
                                              round(float(platz['lon']), 5)]
                break
            if str(kennung).upper() in orte:
                break
    return orte


def instanz_kapitel() -> dict:
    path = DATEN / 'questmerkmale.json'
    if not path.is_file():
        return {}
    daten = json.loads(path.read_text(encoding='utf-8'))
    return {str(k).upper(): str(v).upper() for k, v in (daten.get('instanzen') or {}).items()}


def orte_ergaenzen(rows: list[dict], daten: dict) -> None:
    """Chapters without a place of their own borrow a proven one: the quest
    giver's spot, the objectives of the step that names them, or as an instance
    part the place of their chapter."""
    geber = geber_orte()
    referenzen = {}
    for quest in daten.values():
        eigene = quest.get('t') or []
        if not eigene:
            continue
        for vorher in quest.get('v') or []:
            referenzen.setdefault(str(vorher).upper(), []).extend(eigene)
    for row in rows:
        if row.get('gt') or row.get('t'):
            continue
        kennung = row['i']
        ort = geber.get(kennung)
        if ort:
            row['gt'] = ort
            continue
        eigene, gesehen = [], set()
        for ziel in referenzen.get(kennung, []):
            schluessel = (int(ziel[0]), round(float(ziel[1]), 5), round(float(ziel[2]), 5))
            if schluessel in gesehen:
                continue
            gesehen.add(schluessel)
            eigene.append([schluessel[0], schluessel[1], schluessel[2],
                           ziel[3] if len(ziel) > 3 else ''])
        if eigene:
            row['t'] = eigene[:12]


def baue(lang: str) -> dict:
    lua = lua_rows(PLUGIN / ('Quests_%s.lua' % lang))
    text = (WEB / ('daten-%s.js' % lang)).read_text(encoding='utf-8')
    daten = {str(quest['i']).upper(): quest
             for quest in assignment(text, 'MQL_QUESTS')}
    kapitel = instanz_kapitel()
    gruppen = {}
    reihenfolge = []
    for eintrag in lua:
        kennung = eintrag['id']
        quest = daten.get(kennung)
        if quest is None:
            continue
        volume = next((key.split(':', 1)[1] for key, _ in eintrag['pfad']
                       if key.startswith('volume:')), None)
        story = next(((key, wert) for key, wert in eintrag['pfad'] if key.startswith('story:')), None)
        category = next(((key, wert) for key, wert in eintrag['pfad']
                         if key.startswith('category:')), None)
        if not category:
            continue
        kategorie_id = category[0].split(':', 1)[1]
        roh = category[1]
        if volume:
            gruppe = '%s %s' % (BAND[lang], volume)
            name = sauber(roh)
            art = 'band'
        elif story:
            gruppe = sauber(roh.split(',', 1)[0])
            name = sauber(roh, gruppe)
            art = 'story'
        else:
            gruppe = sauber(roh)
            name = ''
            art = 'arc'
        if gruppe not in gruppen:
            gruppen[gruppe] = {'name': gruppe, 'art': art, 'buecher': {},
                               'ids': [], 'arc': kategorie_id if art == 'arc' else ''}
            reihenfolge.append(gruppe)
        if art == 'arc':
            gruppen[gruppe]['ids'].append(kennung)
        else:
            gruppen[gruppe]['buecher'].setdefault(name, []).append(kennung)

    def gruppen_rang(name):
        eintrag = gruppen[name]
        if eintrag['art'] == 'band':
            m = re.match(r'^(?:Band|Book|Livre)\s+(.+)$', name)
            return (0, roman(m.group(1)) if m else 99, name)
        if eintrag['art'] == 'story':
            return (1, 0, name)
        return (2, GROUP_ORDER.index(eintrag['arc']) if eintrag['arc'] in GROUP_ORDER else 99, name)

    rows = {}
    for eintrag in lua:
        kennung = eintrag['id']
        quest = daten.get(kennung)
        if quest is None:
            continue
        row = {key: quest[key] for key in KEEP if key in quest}
        if kennung in kapitel:
            row['ie'] = kapitel[kennung]
        rows[kennung] = row
    orte_ergaenzen(list(rows.values()), daten)

    liste = []
    for name in sorted(gruppen, key=gruppen_rang):
        gruppe = gruppen[name]
        buecher = []
        for buchname, ids in gruppe['buecher'].items():
            ids.sort(key=lambda k: (kapitel_rang(rows[k].get('n', '')), rows[k].get('n', '')))
            # A prologue chain is the introduction to a book: it has no status of
            # its own, because it never counts towards that book's progress.
            if ist_prolog(buchname):
                for kennung in ids:
                    rows[kennung]['pr'] = 1
            buecher.append({'name': buchname, 'ids': ids})
        buecher.sort(key=lambda buch: buch_rang(buch['name']))
        gruppe['buecher'] = buecher
        gruppe['ids'].sort(key=lambda k: (kapitel_rang(rows[k].get('n', '')), rows[k].get('n', '')))
        gruppe.pop('art', None)
        gruppe.pop('arc', None)
        liste.append(gruppe)
    return {'sprache': lang, 'name': NAME[lang], 'karte': WELTKARTE,
            'gruppen': liste, 'quests': rows}


def main() -> None:
    for lang in LANGS:
        daten = baue(lang)
        ziel = WEB / ('epik-%s.js' % lang)
        ziel.write_text(
            '/* Epic story view. Generated by tools/build_epik.py; it is not part\n'
            ' * of the map catalogue path. */\nwindow.MQL_EPIK_DATEN = %s;\n' %
            json.dumps(daten, ensure_ascii=False, separators=(',', ':')),
            encoding='utf-8')
        gruppen = len(daten['gruppen'])
        buecher = sum(len(g['buecher']) for g in daten['gruppen'])
        print('%s: %d Gruppen, %d Bücher, %d Aufgaben, %.1f KiB' %
              (lang, gruppen, buecher, len(daten['quests']), ziel.stat().st_size / 1024))


if __name__ == '__main__':
    main()
