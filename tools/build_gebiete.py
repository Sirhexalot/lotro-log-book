#!/usr/bin/env python3
"""Build one landscape navigation shared by the quest and the deed map.

The quest catalogue reaches down to sub-maps (Bree, Archet), the deed
catalogue mostly stops at the landscape. Taken alone, each tree showed a
different number of landscapes and map tabs, which made the deed overview look
like another product rather than the same world with other entries.

This tool merges the labels and map ids of both catalogues into one small list.
`app.js` fills missing landscapes and map tabs from it, so both views show the
same navigation; a landscape without entries simply counts zero.

    python3 tools/build_gebiete.py            # all three languages

Result: `web/gebiete-<sprache>.js`, loaded by the map before `app.js`.
"""
import json
from pathlib import Path

HIER = Path(__file__).resolve().parents[1]
SPRACHEN = ('de', 'en', 'fr')


def kataloge(sprache):
    for art in ('quests', 'taten'):
        pfad = HIER / 'daten' / ('%s-%s.json' % (art, sprache))
        if not pfad.is_file():
            continue
        yield art, json.loads(pfad.read_text())


def sammle(sprache):
    regionen = {}
    for art, daten in kataloge(sprache):
        for eintrag in daten.get('quests', []):
            labels = eintrag.get('f') or []
            karten = eintrag.get('fk') or []
            # Both lists describe the same levels; without them there is no
            # landscape to file this entry under.
            if len(labels) < 2 or len(karten) < 2:
                continue
            region = regionen.setdefault(labels[0], {})
            gebiet = region.setdefault(labels[1], {'karte': None, 'unter': {}})
            if karten[1] and not gebiet['karte']:
                gebiet['karte'] = karten[1]
            for nummer in range(2, min(len(labels), len(karten))):
                if karten[nummer]:
                    gebiet['unter'].setdefault(karten[nummer], labels[nummer])
    liste = []
    for name in sorted(regionen, key=lambda text: (text.casefold(), text)):
        gebiete = []
        for gebiet_name in sorted(regionen[name], key=lambda text: (text.casefold(), text)):
            gebiet = regionen[name][gebiet_name]
            if not gebiet['karte'] and not gebiet['unter']:
                continue
            gebiete.append({
                'name': gebiet_name,
                'karte': gebiet['karte'],
                'unter': [[nummer, regionen[name][gebiet_name]['unter'][nummer]]
                          for nummer in sorted(regionen[name][gebiet_name]['unter'])],
            })
        if gebiete:
            liste.append({'name': name, 'gebiete': gebiete})
    return liste


def main() -> int:
    for sprache in SPRACHEN:
        liste = sammle(sprache)
        if not liste:
            raise SystemExit('Keine Katalogdaten für %s; zuerst build_daten.py laufen lassen' % sprache)
        ziel = HIER / 'web' / ('gebiete-%s.js' % sprache)
        ziel.write_text('/* Generated by tools/build_gebiete.py. Do not edit. */\n'
                        'window.MQL_GEBIETE = '
                        + json.dumps({'schema': 1, 'regionen': liste},
                                     ensure_ascii=False, separators=(',', ':'))
                        + ';\n', encoding='utf-8')
        gebiete = sum(len(region['gebiete']) for region in liste)
        unter = sum(len(gebiet['unter']) for region in liste for gebiet in region['gebiete'])
        print('%s: %d Regionen, %d Landschaften, %d Untergebiete -> %s'
              % (sprache, len(liste), gebiete, unter, ziel.name))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())